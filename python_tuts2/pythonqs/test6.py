#to find the length of  a string in python
a="Why fit in, when you are born to stand out!"
print(len(a))   

#to how many time alphabet o is occuring in the string
print(a.count("o"))

#to convert the string to lower case
print(a.lower())

#to convert the string to upper case
print(a.upper())

#convert the string to title case
print(a.title())

#to find the index of sub string
print(a.index("fit in"))
print(a.find("fit in"))