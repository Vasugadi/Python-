arr=[1,2,3,4,5]

ma=arr[0]
mi=arr[len(arr)-1]
for i in arr:
    if(i>ma):
        ma=i
    if(i<mi):
        mi=i


print("The maximum number in array is:",ma)
print("The minimum number in array is:",mi)

