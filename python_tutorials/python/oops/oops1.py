# oops is a programming paradigm which is based on the concept of class and object
# class is a blueprint of an object
# object is an instance of a class
# class is a user defined data type
# class is a collection of data members and member functions
# data members are variables and member functions are functions
# data members are also called as attributes and member functions are also called as methods

# creating a  class
class Student:
    name="ks"

s1=Student()
print(s1.name)


class Brand:
    color="black"
    name="nike"
p1=Brand()
print(p1.color)
print(p1.name)

