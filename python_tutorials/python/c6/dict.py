# dictionaries are used to store data vlaues in key value pairs

#syntax

#empty dictionary

d={}

#dictionary with some data

d={"name":"marco","age":20,"city":"bangalore"}

print(d)

#accessing data from dictionary

print(d["name"])

print(d["age"])

print(d["city"])

#adding data to dictionary

d["gender"]="male"

print(d)

#updating data in dictionary
d["age"]=21