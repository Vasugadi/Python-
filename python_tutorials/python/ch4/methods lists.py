list=[1,2,3,4,5,6,7]
list.append(1)
print(list)

list.insert(0,2)#inserts a value at  a particular index
print(list)

list.remove(1)#removes a value at index1
print(list)

list.sort()#sorts the list
print(list)

list.reverse()#reverses the list
print(list)

list.pop()#removes the last element
print(list)

list.clear()#clears the list
print(list)

list.sort(reverse=True)#sorts the list in reverse order
print(list)

