# identifiers can be combination of uppercase and lowercase letters, digits and underscores.
# They cannot start with a digit.
# They cannot be a reserved word.
# They are case sensitive.
# They can be of any length.
# They can be of any length, but Python interpreter reads only the first 31 characters of the identifier. 
# Python is a case sensitive language. This means that the variables, functions, classes, etc. are treated differently based on the case of the letters. For example, the variables ‘var’, ‘Var’ and ‘VAR’ are all different variables.


### type is used to check the type of the variable
print(type(10))
print(type(10.5))
print(type('hello'))
print(type(True))
# it will give the class of the variable 