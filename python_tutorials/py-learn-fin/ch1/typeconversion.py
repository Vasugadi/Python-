#type casting
#type conversion is the process of converting a value from one type to another type.
#type conversion can be implicit or explicit.
#implicit type conversion is done by the compiler automatically.
#explicit type conversion is done by the programmer manually.
#type conversion can be done between different data types such as int, float, string, etc.
#type conversion can be done using built-in functions such as int(), float(), str(), etc.
#type conversion can also be done using type casting operators such as (int), (float), (str), etc.
#type conversion can be dangerous if not done carefully, as it can lead to loss of data or incorrect results.





a=2.5
b=4
sum=a+b
print(sum)






