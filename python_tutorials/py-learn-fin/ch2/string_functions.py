str="i am a coder"

#functions
print(str.upper()) #to all upper case
print(str.lower()) #to all lower case
print(str.title()) #to first letter of each word to upper case
print(str.capitalize()) #to first letter of the string to upper case
print(str.swapcase()) #to swap upper case to lower case and vice versa
print(str.isupper()) #to check if all the letters are upper case
print(str.islower()) #to check if all the letters are lower case
print(str.isalpha()) #to check if all the letters are alphabets
print(str.isalnum()) #to check if all the letters are alphanumeric
print(str.isnumeric()) #to check if all the letters are numeric
print(str.isdecimal()) #to check if all the letters are decimal
print(str.endswith("coder")) #to check if the string ends with the given string
print(str.startswith("i")) #to check if the string starts with the given string
print(str.find("a")) #to find the index of the given string
print(str.replace("a","o")) #to replace the given string with the given string
print(str.split(" ")) #to split the string into a list of words
print(str.count("a")) #to count the number of times the given string appears in the string

