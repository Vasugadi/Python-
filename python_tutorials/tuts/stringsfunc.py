str="iam a coder from india"

print(str.islower()) # is it lower or not

print(str.isupper()) # is it upper or not

print(str.isalpha()) # is it alphabetic or not

print(str.isdigit()) # is it digit or not

print(str.isalnum()) # is it alphanumeric or not

print(str.isspace()) # is it space or not
print(str.startswith("i")) # is it start with i or not

print(str.endswith("a")) # is it end with a or not
print(str.find("a")) # find the index of a

print(str.rfind("a")) # find the index of a from right side

print(str.count("a")) # count the number of a

print(str.replace("a","o")) # replace a with o

print(str.upper()) # convert all the letters to upper case

print(str.lower()) # convert all the letters to lower case