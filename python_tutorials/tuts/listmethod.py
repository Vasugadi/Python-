list=[1,2,3]
list.append(5) #adds one element at the end of the list
list.sort()# sorts the list in ascending order
list.reverse()# reverses the list
list.sort(reverse=True)# sorts the list in descending order
list.insert(0,6)#inserts a value 6 at index 0
list.remove(3)#removes the first occurrence of 3
list.pop(0)#removes the element at index 0
list.index(2)#returns the index of 2
list.copy()#returns a copy of the list
list.count(2)#returns the number of times 2 appears in the list
list.extend([7,8,9])#adds the elements of the list to the end of the list

list.clear()#removes all the elements in the list